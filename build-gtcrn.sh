#!/bin/bash
# Builds vendor/gtcrn.js: GTCRN speech noise removal as plain JavaScript.
#
# Why plain JavaScript: the NTU COOL player page's Content-Security-Policy has no
# 'wasm-unsafe-eval', so the browser refuses to compile any WebAssembly there (see
# AGENTS.md). We compile GTCRN to WebAssembly without SIMD, then convert it to
# JavaScript with binaryen's wasm2js.
#
# Needs: git, uv, cmake, a C compiler, protobuf (protoc + C++ library) and
# Emscripten (emcc) on PATH. Run: ./build-gtcrn.sh
# If protobuf is not installed system-wide, point PROTOBUF_PREFIX at it,
# e.g. a conda env made with `conda create -p <dir> -c conda-forge libprotobuf protobuf`.
set -euo pipefail
cd "$(dirname "$0")"

# Pinned upstream: https://github.com/sapphi-red/gtcrn-wasm (MIT), with its
# submodules gtcrn (the model, MIT), onnx2c and pffft.
REPO=https://github.com/sapphi-red/gtcrn-wasm.git
COMMIT=24662ff13f184b96edf91f1568e186341a8ac988
SRC=build-cache/gtcrn-wasm
OUT=vendor/gtcrn.js

for tool in git uv cmake cc emcc; do
  command -v "$tool" >/dev/null || { echo "missing tool: $tool" >&2; exit 1; }
done
# Emscripten ships binaryen's wasm2js in upstream/bin, which emsdk_env.sh does not
# put on PATH.
WASM2JS=${WASM2JS:-$(dirname "$(command -v emcc)")/../bin/wasm2js}
[ -x "$WASM2JS" ] || { echo "wasm2js not found at $WASM2JS; set WASM2JS" >&2; exit 1; }

if [ ! -d "$SRC/.git" ]; then
  git clone "$REPO" "$SRC"
fi
git -C "$SRC" checkout --quiet "$COMMIT"
git -C "$SRC" submodule update --init --recursive --depth 1

B=$SRC/build
W=$B/out/scalar
mkdir -p "$W"

# 1-3: upstream steps. Split the model, convert each part to C with onnx2c, and
# check that C natively against the original model in onnxruntime.
(cd "$B" && uv run rewrite_gru.py gtcrn/stream/onnx_models/gtcrn_simple.onnx out)
cmake -S "$B/onnx2c" -B "$B/out/onnx2c-build" -DCMAKE_BUILD_TYPE=Release \
  ${PROTOBUF_PREFIX:+-DCMAKE_PREFIX_PATH="$PROTOBUF_PREFIX"}
cmake --build "$B/out/onnx2c-build" --parallel --target onnx2c
for i in 0 1 2; do
  "$B/out/onnx2c-build/onnx2c" "$B/out/gtcrn_part$i.onnx" > "$B/out/gtcrn_part$i.c"
  cc -O1 -c "-Dentry=entry_p$i" "$B/out/gtcrn_part$i.c" -o "$B/out/native_part$i.o"
done
cc -O1 -o "$B/out/native_check" "$B/native_harness.c" "$B/gtcrn_gru.c" \
  "$B/out/gtcrn_glue.c" "$B/out/gtcrn_gru_weights.c" \
  "$B/out/native_part0.o" "$B/out/native_part1.o" "$B/out/native_part2.o" -lm
(cd "$B" && uv run check_native.py out/native_check gtcrn/stream/onnx_models/gtcrn_simple.onnx)

# 4: WebAssembly without SIMD (wasm2js cannot convert SIMD; pffft then uses its
# plain scalar code). Speed depends on keeping functions small: V8 does not
# optimize a huge function, and wasm2js -O2/-O3 merge all ~800 network nodes
# into one 1.2 MB function, which runs 10x slower. Hence -fno-inline, link -O1
# and wasm2js -O1 (measured 2026-11-05: 1.1 ms vs 12 ms per 16 ms frame).
# -O2 -fno-unroll-loops instead of -O3: unrolled loops make long straight-line
# node functions that V8 takes far longer to optimize. Same output bit for bit;
# warm-up compute for the first 2.4 s of audio 813 -> 353 ms, garbage
# collections 3063 -> 549 per 1300 frames (tools/bench-gtcrn.mjs, 2026-11-06).
for i in 0 1 2; do
  emcc -c -O2 -fno-unroll-loops -fno-inline "-Dentry=entry_p$i" "$B/out/gtcrn_part$i.c" -o "$W/part$i.o"
done
emcc -O1 -I"$B/pffft/include/pffft" \
  "$W/part0.o" "$W/part1.o" "$W/part2.o" \
  "$B/out/gtcrn_glue.c" "$B/out/gtcrn_gru_weights.c" "$B/gtcrn_gru.c" "$B/gtcrn_dsp.c" \
  "$B/pffft/src/pffft.c" "$B/pffft/src/pffft_common.c" \
  --no-entry -sALLOW_MEMORY_GROWTH=0 -sMALLOC=emmalloc \
  -sEXPORTED_FUNCTIONS="['_gtcrn_create','_gtcrn_destroy','_gtcrn_process_48k','_malloc','_free']" \
  -o "$W/gtcrn.wasm"

# 5: WebAssembly -> JavaScript.
"$WASM2JS" -O1 --enable-bulk-memory --enable-bulk-memory-opt \
  --enable-nontrapping-float-to-int --enable-sign-ext --enable-mutable-globals \
  "$W/gtcrn.wasm" -o "$W/gtcrn.js"

# wasm2js imports three file-output functions (pulled in by printf code that
# noise removal never calls) from a module the browser does not have. Replace
# that import with stand-ins that do nothing.
IMPORT="import * as wasi_snapshot_preview1 from 'wasi_snapshot_preview1';"
[ "$(head -1 "$W/gtcrn.js")" = "$IMPORT" ] || { echo "unexpected first line in $W/gtcrn.js" >&2; exit 1; }
mkdir -p vendor
{
  echo "// GENERATED by build-gtcrn.sh from sapphi-red/gtcrn-wasm $COMMIT - do not edit."
  echo "// GTCRN model: MIT (Rong Xiaobin). gtcrn-wasm: MIT (sapphi-red). pffft: BSD-style."
  echo "// Licenses: vendor/LICENSE-gtcrn, vendor/LICENSE-gtcrn-wasm, vendor/LICENSE-pffft."
  echo "const wasi_snapshot_preview1 = { fd_close() { return 0; }, fd_write() { return 0; }, fd_seek() { return 0; } };"
  tail -n +2 "$W/gtcrn.js"
} > "$OUT"
cp "$B/gtcrn/LICENSE" vendor/LICENSE-gtcrn
cp "$SRC/LICENSE" vendor/LICENSE-gtcrn-wasm
cp "$B/pffft/LICENSE.txt" vendor/LICENSE-pffft
echo "wrote $OUT"
