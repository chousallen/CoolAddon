// Builds vendor/rnnoise.js: RNNoise converted from WebAssembly to plain JavaScript.
//
// Why: the NTU COOL player page's Content-Security-Policy has no 'wasm-unsafe-eval',
// so the browser refuses to compile any WebAssembly there - in the page, in the
// add-on's content script and in an AudioWorklet created from it (tested
// 2026-11-05). Plain JavaScript loaded from the add-on's own files is allowed.
//
// Run after `npm install`: `npm run vendor`.
import { execFileSync } from 'node:child_process';
import { copyFileSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';

const pkg = 'node_modules/@sapphi-red/web-noise-suppressor';
const out = 'vendor/rnnoise.js';
mkdirSync('vendor', { recursive: true });

// Non-SIMD build: wasm2js cannot convert SIMD instructions.
execFileSync('node_modules/.bin/wasm2js', ['-O3', `${pkg}/dist/rnnoise.wasm`, '-o', out]);

// wasm2js imports the three helper functions RNNoise needs from a module named
// 'env'. No such module exists in the browser, so define them here instead.
const IMPORT_LINE = "import * as env from 'env';";
const ENV = `// Helper functions RNNoise imports (normally supplied by Emscripten's loader).
const env = {
  emscripten_memcpy_big(dest, src, num) {
    new Uint8Array(memory.buffer).copyWithin(dest, src, src + num);
  },
  // The 16 MB starting memory is plenty; report "cannot grow" if ever asked.
  emscripten_resize_heap() { return 0; },
  __assert_fail() { throw new Error('rnnoise: assertion failed'); },
};`;
const js = readFileSync(out, 'utf8');
if (!js.startsWith(IMPORT_LINE)) throw new Error(`unexpected first line in ${out}`);
writeFileSync(out, `// GENERATED by build-vendor.mjs from ${pkg}/dist/rnnoise.wasm - do not edit.\n` +
  `// RNNoise: BSD-3-Clause (Xiph.Org, Jean-Marc Valin). WebAssembly build: @shiguredo/rnnoise-wasm,\n` +
  `// Apache-2.0. Packaged by @sapphi-red/web-noise-suppressor, MIT (see LICENSE-web-noise-suppressor).\n` +
  js.replace(IMPORT_LINE, ENV));
copyFileSync(`${pkg}/LICENSE`, 'vendor/LICENSE-web-noise-suppressor');
console.log(`wrote ${out}`);
